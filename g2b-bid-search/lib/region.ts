// 기관명에서 시·도를 추정한다. API에 수요기관 주소가 없어서 이름으로 판단하며, 판단할 수 없으면 '전국·기타'.

const FULL: [string, string][] = [
  ["서울특별시", "서울"],
  ["부산광역시", "부산"],
  ["대구광역시", "대구"],
  ["인천광역시", "인천"],
  ["전남광주통합특별시", "전남광주"],
  ["광주광역시", "광주"],
  ["대전광역시", "대전"],
  ["울산광역시", "울산"],
  ["세종특별자치시", "세종"],
  ["경기도", "경기"],
  ["강원특별자치도", "강원"],
  ["강원도", "강원"],
  ["충청북도", "충북"],
  ["충청남도", "충남"],
  ["전북특별자치도", "전북"],
  ["전라북도", "전북"],
  ["전라남도", "전남"],
  ["경상북도", "경북"],
  ["경상남도", "경남"],
  ["제주특별자치도", "제주"],
];

const SHORT = ["서울", "부산", "대구", "인천", "광주", "대전", "울산", "세종", "경기", "강원", "충북", "충남", "전북", "전남", "경북", "경남", "제주"];

export const REGION_ORDER = [...new Set(FULL.map(([, s]) => s)), "전국·기타"];

export function regionOf(name: string): string {
  const s = name || "";
  for (const [full, short] of FULL) if (s.includes(full)) return short;
  // '한국농어촌공사 경남지역본부', '서울교통공사' 같은 줄임 이름
  for (const short of SHORT) {
    const re = new RegExp(`(^|[\\s(])${short}`);
    if (re.test(s)) return short;
  }
  return "전국·기타";
}
